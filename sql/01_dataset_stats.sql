-- Общая статистика датасета MovieLens 100K
-- Считаем размеры таблицы и разреженность матрицы "пользователи x фильмы"

-- Сколько всего оценок, уникальных пользователей и фильмов
SELECT 
    COUNT(*) AS num_ratings,
    COUNT(DISTINCT user_id) AS num_users,
    COUNT(DISTINCT item_id) AS num_movies
FROM ratings;

-- Разреженность: доля заполненных ячеек в матрице
-- = всего оценок / (пользователи * фильмы)
-- У нас получится ~6%, то есть 94% ячеек пустые
